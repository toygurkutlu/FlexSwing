package io.github.toygurkutlu.flexswing.components.navigation_view.enums;

/**
 * Represents the position of the text according to the icon.
 */
public enum TextPosition {
    /**
     * Represents the position of the text. The text will be placed on the left side, the icon will be placed
     * on the right side.
     * */
    LEFT,

    /**
     * Represents the position of the text. The text will be placed on the right side, the icon will be placed
     * on the left side.
     * */
    RIGHT
}
